import { createRequire } from "node:module";
import { readFile,readdir,writeFile } from "node:fs/promises";
import { join,resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root=fileURLToPath(new URL("./",import.meta.url));
const deps=resolve(process.argv[2]??root);
const require=createRequire(join(deps,"package.json"));
const { build }=require("esbuild");
const banner="// Generated by build-webauthn.mjs. Third-party terms in webauthn-notices.txt.";
const packageNames=new Set();

for (const [entry,path] of [
  ['export { generateRegistrationOptions, generateAuthenticationOptions, verifyRegistrationResponse, verifyAuthenticationResponse } from "@simplewebauthn/server";',"webauthn-vendor.mjs"],
  ['export { startAuthentication, startRegistration } from "@simplewebauthn/browser";',"docs/assets/webauthn-vendor.js"],
]) {
  const result=await build({
    absWorkingDir:deps,
    stdin:{contents:entry,resolveDir:deps},
    bundle:true,platform:"browser",format:"esm",target:"es2022",minify:true,legalComments:"eof",
    banner:{js:banner},outfile:join(root,path),metafile:true,
  });
  for (const file of Object.values(result.metafile.outputs).flatMap(content=>Object.keys(content.inputs))) {
    const path=file.split("node_modules/").at(-1).split("/");
    if(path.length>1) packageNames.add(path.slice(0,path[0].startsWith("@")?2:1).join("/"));
  }
}

const licenses=[];
for (const name of [...packageNames].sort()) {
  const directory=join(deps,"node_modules",name);
  const metadata=JSON.parse(await readFile(join(directory,"package.json"),"utf8"));
  const names=(await readdir(directory)).filter(file=>/^licen[sc]e(?:\.|$)|^copying(?:\.|$)/i.test(file));
  if (!names.length) throw new Error("Licenza mancante per "+name);
  const content=await Promise.all(names.map(file=>readFile(join(directory,file),"utf8")));
  licenses.push(name+" "+metadata.version+"\n"+content.join("\n").trim());
}
await writeFile(join(root,"webauthn-notices.txt"),licenses.join("\n\n"));
